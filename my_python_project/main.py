# --- БЛОК 1: ОПРЕДЕЛЕНИЕ ИНСТРУМЕНТОВ (ФУНКЦИЙ) ---


def get_mood_input() -> int:
    """
    (Инструмент 1)
    Запрашивает у пользователя настроение (1-5)
    и "запирает" его, пока ввод не станет корректным.
    Возвращает (return) проверенное число (int).
    """

    # (Наследие Дня 3) Вложенный цикл валидации
    while True:
        mood_str = input("Настроение (1-5): ")

        try:
            # (Наследие Дня 1) Превращаем str в int
            mood_int = int(mood_str)

            # (Наследие Дня 3) Логика диапазона
            if 1 <= mood_int <= 5:
                return mood_int  # <- ВЫХОД из функции
            else:
                print("Ошибка: Настроение должно быть от 1 до 5.")

        except ValueError:
            # (Наследие Дня 3) Логика EAFP
            print("Ошибка: Введите, пожалуйста, ЧИСЛО (1, 2, 3, 4 или 5).")


def analyze_entries(entries: list) -> None:
    """
    (Инструмент 2)
    Принимает (как аргумент) список словарей 'entries'.
    Рассчитывает и печатает анализ.
    Ничего не возвращает (поэтому '-> None').
    """

    # (Наследие Дня 3) Проверка на "Truthiness"
    if not entries:
        print("\nВы не сделали ни одной записи. Анализировать нечего.")
        return  # <- ВЫХОД из функции (т.к. анализировать нечего)

    print("\n===============================")
    print("Анализ Вашего Дневника:")

    total_entries = len(entries)
    print(f"Всего записей: {total_entries}")

    total_mood = 0

    # (Наследие Дня 3) Цикл 'for'
    for entry in entries:
        total_mood += entry["mood"]

    average_mood = total_mood / total_entries
    print(f"Среднее настроение: {average_mood:.1f} / 5")


# --- БЛОК 2: ГЛАВНАЯ ЛОГИКА (ДИРИЖЕР) ---


def main():
    """
    (Дирижер)
    Главная функция, которая запускает программу.
    """
    print("--- Система Учета Настроения (СУЦН) v0.3 ---")
    print("Введите 'stop' в поле 'дата', чтобы закончить и получить анализ.")

    # (Наследие Дня 2) Список 'diary_entries' теперь ЛОКАЛЬНЫЙ (L)
    # Он живет только внутри функции main().
    diary_entries = []

    # (Наследие Дня 3) Основной цикл ввода
    while True:
        date = input("\nДата (гггг-мм-дд): ")
        if date == "stop":
            break  # Выходим из цикла while

        # --- ВЫЗОВ ИНСТРУМЕНТА 1 ---
        # Мы заменяем 15 строк 'try-except'
        # одним чистым вызовом функции.
        mood = get_mood_input()

        notes = input("Заметки: ")

        # (Наследие Дня 2) Упаковываем в словарь
        entry = {
            "date": date,
            "mood": mood,  # <- Здесь уже 100% проверенный int
            "notes": notes,
        }
        diary_entries.append(entry)
        print("--- Запись добавлена! ---")

    # --- ВЫЗОВ ИНСТРУМЕНТА 2 ---
    # Передаем собранный список 'diary_entries'
    # в "черный ящик" анализатора.
    analyze_entries(diary_entries)

    print("\n--- Работа программы завершена. ---")


# --- БЛОК 3: ТОЧКА ВХОДА ---

# Это стандартная идиома Python.
# Она означает: "Если этот файл (main.py) запустили
# НАПРЯМУЮ, а не импортировали, ...
if __name__ == "__main__":
    # ...тогда выполни нашу главную функцию-дирижер."
    main()
