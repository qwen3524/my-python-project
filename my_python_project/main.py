print("--- Система Учета Настроения (СУЦН) v0.2 ---")
print("введите 'стоп' в поле'дата'что бы закончить.")
# 1. Наш главный контейнер: СПИСОК.
# Он будет хранить СЛОВАРИ.
diary_entries = []
# 2. Бесконечный цикл для ввода данных
while True:
    # 3. Получаем ввод (Навык Дня 1)
    date = input("дата: (дд-мм-гггг):")
    # 4. Проверка на выход
    if date == "стоп":
        break  # Выходим из цикла while True
    # --- Начало Валидации Настроения ---
    # Мы "запираем" пользователя во вложенном цикле,
    # пока не получим правильное число.
    while True:
        mood_str = input("настроение(1-5):")
        try:
            mood_int = int(mood_str)
            # (Логика Дня 3) Проверяем диапазон
            if 1 <= mood_int <= 5:
                # Все отлично! Выходим из ВЛОЖЕННОГО цикла
                break
            else:
                # Число введено, но оно не в диапазоне
                print("ошибка число долно быть введено в диапазоне от 1 до 5")
        # 'continue' не нужен, цикл и так начнется заново
        except ValueError:
            # (Логика Дня 3) Охрана сработала! int() не смог
            # # обработать ввод (например, "пять" или "abc").
            print("Ошибка: Введите, пожалуйста, ЧИСЛО (1, 2, 3, 4 или 5).")
    # 'continue' не нужен, цикл и так начнется заново
    # --- Конец Валидации Настроения ---
    notes = input("заметки:")
    ## (Наследие Дня 2) Упаковываем в словарь
    # ВАЖНО: Мы сохраняем 'mood_int', а не 'mood_str'
    entry = {
        "date": date,
        "mood": mood_int,  # <- Теперь это ЧИСЛО!
        "notes": notes,
    }
    # 6. Добавляем СЛОВАРЬ в СПИСОК (Навык Дня 2)
    diary_entries.append(entry)
    print("запись добавлена")
# ================================================
# БЛОК 2: АНАЛИЗ ДАННЫХ
# ================================================

# (Логика Дня 3) Концепция "Truthiness"
# if diary_entries: эквивалентно if len(diary_entries) > 0:
# Это проверка, что список не пустой
if diary_entries:
    print("/=======================================")
    print("анализ ваших записей в дневнике")
    # Считаем общее количество записей
    total_entries = len(diary_entries)
    print(f"всего записей: {total_entries}")
    # Считаем среднее настроение
    total_mood = 0
    # (Цикл 'for' Дня 3)
    # Перебираем наш список словарей
    for entry in diary_entries:
        # 'entry' - это ОДИН словарь (напр. {'date': '...', 'mood': 5, ...})
        # Мы берем значение по ключу 'mood'
        total_mood = total_mood + entry["mood"]
        # Считаем среднее
    average_mood = total_mood / total_entries
    # :.1f - синтаксис f-строки для округления до 1 знака после запятой
    print(f"среднее настроение:{average_mood:.1f}/5")
    # (Логика Дня 3) Блок 'else'
else:
    print("\nВы не сделали ни одной записи. Анализировать нечего.")
print("--- Работа программы завершена. ---")
